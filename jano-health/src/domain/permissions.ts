/**
 * Evaluates whether a role holds a specific capability or permission string.
 * Supports both dot notation ("patient.read", "medication.prescribe")
 * and colon notation ("patient:read", "clinical:prescribe").
 */
export function hasCapability(role: RoleType, capabilityOrPermission: Capability | Permission | string): boolean {
  const roleDef = ROLE_DEFINITIONS[role];
  if (!roleDef) return false;

  // Check if direct Permission match in roleDef.permissions
  if (roleDef.permissions.includes(capabilityOrPermission as Permission)) {
    return true;
  }

  // Check if mapped capability
  const mappedPermissions = CAPABILITY_TO_PERMISSIONS[capabilityOrPermission as Capability];
  if (mappedPermissions) {
    return mappedPermissions.some((p) => roleDef.permissions.includes(p));
  }

  // Support reverse colon conversion if dot was passed
  const colonPerm = capabilityOrPermission.replace('.', ':') as Permission;
  if (roleDef.permissions.includes(colonPerm)) {
    return true;
  }

  return false;
}

/**
 * Checks whether a user entity (with role and optional capabilities array) can perform an action.
 */
export function canUserPerform(
  user: { role: RoleType; capabilities?: string[] } | null | undefined,
  capabilityOrPermission: Capability | Permission | string
): boolean {
  if (!user) return false;
  if (user.capabilities && user.capabilities.length > 0) {
    if (user.capabilities.includes(capabilityOrPermission as Capability)) return true;
    const dotCap = capabilityOrPermission.replace(':', '.') as Capability;
    if (user.capabilities.includes(dotCap)) return true;
  }
  return hasCapability(user.role, capabilityOrPermission);
}

/**
 * Standard typed authorization error returned when an unauthorized clinical action is attempted.
 */
export class AuthorizationError extends Error {
  public readonly code = 'AUTHORIZATION_DENIED';
  public readonly requiredCapability: string;
  public readonly userRole: RoleType;
  public readonly actionDescription: string;

  constructor(requiredCapability: string, userRole: RoleType, actionDescription?: string) {
    const roleTitle = ROLE_DEFINITIONS[userRole]?.title || userRole;
    const desc = actionDescription || requiredCapability;
    const message = `Your current role (${roleTitle}) does not have permission to ${desc}. Consult an authorized clinician or supervisor.`;
    super(message);
    this.name = 'AuthorizationError';
    this.requiredCapability = requiredCapability;
    this.userRole = userRole;
    this.actionDescription = desc;
  }
}

