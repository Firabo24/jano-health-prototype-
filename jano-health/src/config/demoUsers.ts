/**
 * Get all available demo users including canonical and mapped legacy entries
 */
export function getAllDemoUsers(): DemoUser[] {
  return CANONICAL_DEMO_USERS;
}

/**
 * Find demo user by ID, username, or role
 */
export function findDemoUser(identifier: string): DemoUser | undefined {
  const normalized = identifier.toLowerCase().trim();
  
  // Direct ID match
  const byId = CANONICAL_DEMO_USERS.find((u) => u.id.toLowerCase() === normalized);
  if (byId) return byId;

  // Direct username match
  const byUsername = CANONICAL_DEMO_USERS.find((u) => u.username.toLowerCase() === normalized);
  if (byUsername) return byUsername;

  // Role match
  const byRole = CANONICAL_DEMO_USERS.find((u) => u.role.toLowerCase() === normalized);
  if (byRole) return byRole;

  // Legacy alias check
  const legacy = LEGACY_TEST_USER_ALIASES[identifier];
  if (legacy && legacy.role) {
    const roleMatch = CANONICAL_DEMO_USERS.find((u) => u.role === legacy.role);
    if (roleMatch) {
      return {
        ...roleMatch,
        ...legacy,
      } as DemoUser;
    }
  }

  return undefined;
}
